"""Generated Sokoban maps - solvable by construction or BFS.

Auto-generated by src/env/map_generator.py. Do not edit by hand.
To regenerate: python src/env/map_generator.py

Walled maps (hand-authored, with interior walls) live in walled_maps.json.
To add walled maps: edit walled_maps.json directly.
"""

import json
import os

_WALLED_CACHE: dict | None = None


def _walled_data() -> dict:
    global _WALLED_CACHE
    if _WALLED_CACHE is None:
        here = os.path.dirname(os.path.abspath(__file__))
        path = os.path.join(here, "walled_maps.json")
        if not os.path.exists(path):
            raise FileNotFoundError(
                f"Walled map data not found at {path}.\n"
                "Create src/utils/walled_maps.json with keys '1box', '2box', '3box'."
            )
        with open(path) as f:
            _WALLED_CACHE = json.load(f)
    return _WALLED_CACHE


def build_walled_1box_maps() -> list:
    return _walled_data().get("1box", [])


def build_walled_2box_maps() -> list:
    return _walled_data().get("2box", [])


def build_walled_3box_maps() -> list:
    return _walled_data().get("3box", [])


def _m(name, diff, h, w, player, boxes, goals, max_steps=120):
    return {"map_name": name, "difficulty": diff, "height": h, "width": w,
            "player": player, "boxes": boxes, "goals": goals, "max_steps": max_steps}


